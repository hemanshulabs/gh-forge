package runtime

import (
	"context"
	"fmt"
	"os/exec"
	"strings"

	"github.com/dlvhdr/gh-dash/v4/internal/agent"
)

// SafeExecutor handles write actions (comments, labels, closing) with mandatory opt-in and dry-run safety.
type SafeExecutor struct {
	DryRun bool
}

func NewSafeExecutor(dryRun bool) *SafeExecutor {
	return &SafeExecutor{DryRun: dryRun}
}

// PostPRComment posts agent findings as a PR comment.
func (e *SafeExecutor) PostPRComment(ctx context.Context, repo string, prNumber int, result *agent.AgentResult) (string, error) {
	body := FormatCommentMarkdown(result)
	if e.DryRun {
		return fmt.Sprintf("[DRY-RUN] Would post comment to PR #%d in %s:\n%s", prNumber, repo, body), nil
	}

	args := []string{"pr", "comment", fmt.Sprint(prNumber), "-R", repo, "-b", body}
	cmd := exec.CommandContext(ctx, "gh", args...)
	output, err := cmd.CombinedOutput()
	if err != nil {
		return "", fmt.Errorf("failed to post PR comment via 'gh': %w (%s)", err, strings.TrimSpace(string(output)))
	}
	return fmt.Sprintf("Successfully posted comment to PR #%d", prNumber), nil
}

// PostIssueComment posts agent findings as an issue comment.
func (e *SafeExecutor) PostIssueComment(ctx context.Context, repo string, issueNumber int, result *agent.AgentResult) (string, error) {
	body := FormatCommentMarkdown(result)
	if e.DryRun {
		return fmt.Sprintf("[DRY-RUN] Would post comment to Issue #%d in %s:\n%s", issueNumber, repo, body), nil
	}

	args := []string{"issue", "comment", fmt.Sprint(issueNumber), "-R", repo, "-b", body}
	cmd := exec.CommandContext(ctx, "gh", args...)
	output, err := cmd.CombinedOutput()
	if err != nil {
		return "", fmt.Errorf("failed to post issue comment via 'gh': %w (%s)", err, strings.TrimSpace(string(output)))
	}
	return fmt.Sprintf("Successfully posted comment to Issue #%d", issueNumber), nil
}

// ApplyIssueLabels applies suggested labels to an issue.
func (e *SafeExecutor) ApplyIssueLabels(ctx context.Context, repo string, issueNumber int, labels []string) (string, error) {
	if len(labels) == 0 {
		return "No labels to apply.", nil
	}
	if e.DryRun {
		return fmt.Sprintf("[DRY-RUN] Would apply labels %v to Issue #%d in %s", labels, issueNumber, repo), nil
	}

	args := []string{"issue", "edit", fmt.Sprint(issueNumber), "-R", repo}
	for _, l := range labels {
		args = append(args, "--add-label", l)
	}

	cmd := exec.CommandContext(ctx, "gh", args...)
	output, err := cmd.CombinedOutput()
	if err != nil {
		return "", fmt.Errorf("failed to apply labels via 'gh': %w (%s)", err, strings.TrimSpace(string(output)))
	}
	return fmt.Sprintf("Applied labels %v to Issue #%d", labels, issueNumber), nil
}

// FormatCommentMarkdown converts AgentResult into GitHub Markdown.
func FormatCommentMarkdown(result *agent.AgentResult) string {
	var b strings.Builder
	b.WriteString(fmt.Sprintf("### Forge AI %s Findings\n\n", result.Role))
	b.WriteString(fmt.Sprintf("> **Summary**: %s\n\n", result.Summary))

	if len(result.Findings) == 0 {
		b.WriteString("No issues or warnings found.\n")
		return b.String()
	}

	b.WriteString(fmt.Sprintf("**Identified %d finding(s):**\n\n", len(result.Findings)))
	for i, f := range result.Findings {
		loc := "General"
		if f.File != "" {
			if f.Line > 0 {
				loc = fmt.Sprintf("`%s:%d`", f.File, f.Line)
			} else {
				loc = fmt.Sprintf("`%s`", f.File)
			}
		}

		b.WriteString(fmt.Sprintf("#### %d. [%s] %s (Confidence: %.0f%%)\n", i+1, strings.ToUpper(string(f.Severity)), loc, f.Confidence*100))
		b.WriteString(fmt.Sprintf("%s\n\n", f.Explanation))
		if f.SuggestedFix != "" {
			b.WriteString("**Suggested Fix:**\n```\n")
			b.WriteString(f.SuggestedFix)
			b.WriteString("\n```\n\n")
		}
	}

	b.WriteString("\n---\n*Generated by Forge CLI AI Agents*")
	return b.String()
}
